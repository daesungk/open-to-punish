/* Korean particles: object marker 을/를 and direction marker 으로/로. */
function koHasFinal(word) {
  const c = word.charCodeAt(word.length - 1);
  if (c >= 0xAC00 && c <= 0xD7A3) return (c - 0xAC00) % 28 !== 0;
  return false;
}
function koObj(word) { return word + (koHasFinal(word) ? "을" : "를"); }
function koRo(sq) {
  // squares end in a digit read as Korean numbers: 3 (삼) and 6 (육) take 으로; 1, 7, 8 end in ㄹ and take 로
  return /[36]$/.test(sq) ? "으로" : "로";
}

