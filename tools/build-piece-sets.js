#!/usr/bin/env node
// Packs the SVG files in pieces/<set>/ into js/piece-sets.js as data URIs, so the
// app works when opened straight from the folder (no server needed) and offline.
// Run after adding or changing a piece set: node tools/build-piece-sets.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const ORDER = ["wK", "wQ", "wR", "wB", "wN", "wP", "bK", "bQ", "bR", "bB", "bN", "bP"];
const out = {};
for (const set of fs.readdirSync(path.join(root, "pieces"))) {
  const dir = path.join(root, "pieces", set);
  if (!fs.statSync(dir).isDirectory()) continue;
  out[set] = {};
  for (const p of ORDER) {
    const svg = fs.readFileSync(path.join(dir, p + ".svg"));
    out[set][p] = "data:image/svg+xml;base64," + svg.toString("base64");
  }
}
fs.writeFileSync(path.join(root, "js", "piece-sets.js"),
  "/* Generated by tools/build-piece-sets.js from pieces/. Licenses: see pieces/<set>/LICENSE.txt */\nconst PIECE_SETS = " + JSON.stringify(out) + ";\n");
console.log("Packed piece sets: " + Object.keys(out).join(", "));
